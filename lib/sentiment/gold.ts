import type { Sentiment } from "../sentiment";

/* ---------------------------------------------------------------------------
   Headlines with the label a careful reader gives them, to measure a tagger
   against. FinGPT measures its sentiment models on public news datasets
   (Financial PhraseBank, FiQA, Twitter Financial News); those are licensed for
   non-commercial use and are not copied here. These are written for this
   desk, in the style of the feeds it reads, and labelled by the rule the model
   analyst is given: what the headline implies for the company's share price,
   judged from the headline alone, from the point of view of the first company
   named. Routine coverage, advice and speculation are neutral.

   Two splits, so the number reported is not the number tuned:

   - DEV was written first, and the tagger in lexicon.ts was fitted to it. It
     says nothing about accuracy; it is a regression guard.
   - HELD_OUT was written after the tagger was frozen and was scored once. It
     is the figure to read. Its history is below: a held-out set that has been
     scored and then used to improve the tagger stops being held out.

   The same person wrote the tagger and both sets, so even HELD_OUT flatters
   it. The labels are one reader's judgement; a headline can be argued either
   way. Add your own labelled headlines (scripts/benchmark-sentiment.ts --gold)
   to measure the tagger against what you would say.
--------------------------------------------------------------------------- */

// What makes a headline hard, so the benchmark can say where a tagger fails.
export type Kind =
  | "plain" // explicit sentiment words
  | "phrase" // a fixed expression: "raises guidance", "profit warning"
  | "numeric" // direction carried by a percentage or a figure
  | "analyst" // a rating or price-target change
  | "negation" // "not as weak as feared", "avoids a strike"
  | "contrast" // "despite", "but": two clauses that disagree
  | "routine" // scheduled or administrative: no news in it
  | "advice"; // a question, a listicle, a "should you buy"

export interface Gold {
  title: string;
  label: Sentiment;
  kind: Kind;
}

